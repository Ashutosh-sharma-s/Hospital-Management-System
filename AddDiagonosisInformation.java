    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String patientid = jTextField1.getText();
        try {
            Statement st = con.createStatement(ResultSet.TYPE_SCROLL_INSENSITIVE, ResultSet.CONCUR_READ_ONLY);
            ResultSet rs = st.executeQuery("select *from addnewpatientrecord where patientid='" + patientid + "'");
            jTable1.setModel(DbUtils.resultSetToTableModel(rs));
            if (!rs.first()) {
                jLabel2.setVisible(true);
            } else {
                jLabel2.setVisible(false);
                jTextField1.setEditable(false);
                flag = 1;
            }
        } catch (SQLException ex) {
            Logger.getLogger(AddDiagonosisInformation.class.getName()).log(Level.SEVERE, null, ex);

            JOptionPane.showMessageDialog(this, "Connection Error");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        if (flag == 1) {
            String PatientID = jTextField1.getText();
            String Symptom = jTextField2.getText();
            String Diagnosis = jTextField3.getText();
            String Medicines = jTextField4.getText();
            String Wardreq;
            String TypeWard;
            if (jCheckBox2.isSelected()) {
                Wardreq = "Yes";
                TypeWard = (String) jComboBox1.getSelectedItem();
            } else {
                Wardreq = "No";
                TypeWard = "";

            }
            try {
                pst = (PreparedStatement) con.prepareStatement("insert into patientreport"
                        + "(PatientID,Symptom,Diagnosis,Medicines,Wardreq,TypeWard) "
                        + "values(?,?,?,?,?,?)");
                pst.setString(1, PatientID);
                pst.setString(2, Symptom);
                pst.setString(3, Diagnosis);
                pst.setString(4, Medicines);
                pst.setString(5, Wardreq);
                pst.setString(6,TypeWard);
                pst.executeUpdate();
                JOptionPane.showMessageDialog(null, "Successfully Updated");
                setVisible(false);
                new AddDiagonosisInformation().setVisible(true);

            } catch (SQLException ex) {
                
                Logger.getLogger(AddDiagonosisInformation.class.getName()).log(Level.SEVERE, null, ex);
            }

        } else {
            JOptionPane.showMessageDialog(null, "PatientID Field is Empty!");
        }
    }//GEN-LAST:event_jButton2ActionPerformed

