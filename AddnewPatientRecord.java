    private void SaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SaveActionPerformed
        // TODO add your handling code here:
        String patientid = jTextField1.getText();
        String name = jTextField2.getText();
        String contactnumber = jTextField3.getText();
        String age = jTextField4.getText();
        String gender = (String) jComboBox1.getSelectedItem();
        String bloodgroup = jTextField5.getText();
        String anymajordiseasesufferedearlier = jTextField6.getText();

        if (patientid.isEmpty() && name.isEmpty() && contactnumber.isEmpty() && age.isEmpty() 
                && gender.isEmpty() && bloodgroup.isEmpty() && anymajordiseasesufferedearlier.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Enter a Recored And Fill it");
        } else {
            try {
                pst = (PreparedStatement) con.prepareStatement("insert into addnewpatientrecord"
                        + "(patientid,name,contactnumber,age,gender,bloodgroup,anymajordiseasesufferedearlier) "
                        + "values(?,?,?,?,?,?,?)");
                pst.setString(1, patientid);
                pst.setString(2, name);
                pst.setString(3, contactnumber);
                pst.setString(4, age);
                pst.setString(5, gender);
                pst.setString(6, bloodgroup);
                pst.setString(7, anymajordiseasesufferedearlier);

                pst.executeUpdate();
                JOptionPane.showMessageDialog(this, "Record Save");
                 setVisible(false);
                new AddnewPatientRecord().setVisible(true);
               
                jTextField1.setText("");
                jTextField2.setText("");
                jTextField3.setText("");
                jTextField4.setText("");
                jComboBox1.setSelectedItem("");
                jTextField5.setText("");
                jTextField6.setText("");
            } catch (SQLException ex) {
                Logger.getLogger(AddnewPatientRecord.class.getName()).log(Level.SEVERE, null, ex);
            }
        }

    }//GEN-LAST:event_SaveActionPerformed

